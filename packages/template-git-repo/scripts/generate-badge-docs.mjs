#!/usr/bin/env node
/**
 * Generate `docs/BADGES.md` from the badge catalog in `src/badges.js`.
 *
 * The setup instructions are the reason this package exists — a badge whose
 * prerequisites nobody wrote down is a badge that reads "unknown" forever — so
 * they live next to the badge definition and the docs are derived from them.
 * `test/docs.test.js` fails if the committed file drifts from the catalog.
 *
 * Usage: node scripts/generate-badge-docs.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BADGES, GROUPS } from '../src/badges.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DOCS_PATH = path.join(HERE, '..', 'docs', 'BADGES.md');

const GROUP_TITLES = {
  identity: 'Identity — what this project is',
  quality: 'Quality — is it working, is it tested, is it shipped',
  community: 'Community — is it alive, can I join',
  stack: 'Stack — what it is built with',
};

const FLAG_FOR = {
  doi: '--doi <10.5281/zenodo.NNNNNNN>',
  websiteUrl: '--website <url>',
  docsUrl: '--docs <url>',
  apiUrl: '--api <url>',
  youtubeUrl: '--youtube <url>',
  uptimeUrl: '--uptime <url>',
  testReportUrl: '--test-report <url>',
  discordId: '--discord-id <id>',
  discordInvite: '--discord-invite <url>',
  stack: '--stack <A,B,C>',
  cloudflareDeploy: '--cloudflare-deploy',
  npmPackage: '--npm-package <name>',
  workflowFile: '--workflow <file>',
  stackblitzUrl: '--stackblitz <url>',
  codecovFlag: '--codecov-flag <name>',
};

/** @returns {string} the full BADGES.md text */
export function generate() {
  const lines = [
    '<!-- Generated by scripts/generate-badge-docs.mjs from src/badges.js — edit the catalog, not this file. -->',
    '',
    '# Badge setup',
    '',
    'Every badge in the template, what it actually measures, and what you have to do',
    'outside this repo before it shows anything real.',
    '',
    'The CLI leaves out any badge whose inputs it does not have, and prints which ones',
    'it left out and why. Re-run it with the flag from the table below to add one:',
    '',
    '```bash',
    'bunx template-git-repo --badges-only --discord-id 1110227955554209923 --discord-invite https://discord.gg/xxxx',
    '```',
    '',
    'The block lives between `<!-- template-git-repo:badges:start -->` and',
    '`<!-- template-git-repo:badges:end -->` in your README. Re-running replaces what is',
    'between the markers and nothing else, so it is safe to run again after you publish a',
    'package or finish setting up Codecov.',
    '',
    '## Index',
    '',
    '| Badge | Needs | Flag |',
    '| --- | --- | --- |',
  ];

  for (const badge of BADGES) {
    const needs = badge.needs.length > 0 ? badge.needs.join(', ') : '—';
    // Backticks matter here: several flags carry `<angle brackets>`, which a
    // Markdown renderer would otherwise eat as an HTML tag.
    const flags = badge.needs.map((need) => `\`${FLAG_FOR[need] ?? need}\``).join(' ') || 'on by default';
    lines.push(`| [${badge.title}](#${badge.id}) \`${badge.id}\` | ${needs} | ${flags} |`);
  }

  for (const group of GROUPS) {
    const inGroup = BADGES.filter((badge) => badge.group === group);
    if (inGroup.length === 0) continue;

    lines.push('', `## ${GROUP_TITLES[group] ?? group}`, '');

    for (const badge of inGroup) {
      lines.push(
        `### ${badge.id}`,
        '',
        `**${badge.title}**`,
        '',
        badge.setup,
        '',
      );

      if (badge.needs.length > 0) {
        const flags = badge.needs.map((need) => `\`${FLAG_FOR[need] ?? need}\``).join(' ');
        lines.push(`Enable with: ${flags}`, '');
      } else {
        lines.push('Included by default — no configuration needed.', '');
      }
    }
  }

  lines.push(
    '## Removing one',
    '',
    '```bash',
    'bunx template-git-repo --badges-only --exclude commit-activity,last-commit',
    '```',
    '',
    'Or edit the block between the markers directly — the CLI only rewrites it when you',
    'run it again.',
    '',
    '## Why some badges stay grey',
    '',
    '| Badge reads | Almost always means |',
    '| --- | --- |',
    '| Codecov: `unknown` | No upload has landed yet. Check the Codecov dashboard, not the badge — a missing `CODECOV_TOKEN` and a repo that was never added look identical from here. |',
    '| CI: `no status` | The workflow filename in the badge URL does not match a file in `.github/workflows/`, or it has never run on the branch in `?branch=`. |',
    '| npm: `invalid` | The package name is not on the registry, or it is scoped and the scope is missing from the URL. |',
    '| Discord: `invite` instead of a count | The server widget is off. Server Settings → Widget → Enable Server Widget. |',
    '| Stars/last-commit: `repo not found` | shields.io cannot read private repos. |',
    '',
  );

  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n')}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const generated = generate();

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(DOCS_PATH) ? fs.readFileSync(DOCS_PATH, 'utf8') : '';
    if (current !== generated) {
      console.error('docs/BADGES.md is out of date — run: npm run docs:badges');
      process.exit(1);
    }
    console.log('docs/BADGES.md is up to date');
  } else {
    fs.mkdirSync(path.dirname(DOCS_PATH), { recursive: true });
    fs.writeFileSync(DOCS_PATH, generated);
    console.log(`Wrote ${DOCS_PATH}`);
  }
}
